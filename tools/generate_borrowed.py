import argparse
from pathlib import Path
import re

VERSION='3.14.4'
DIRECTIVE=re.compile(r'^// @Borrow function (\w+) from (\S+) \[([^\]]+)\] as (\w+)\s*$',re.M)


def code_mask(source):
    """Keep token offsets while blanking C comments and string/char literals."""
    token=re.compile(r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'',re.S)
    return token.sub(lambda match: ''.join('\n' if c=='\n' else ' ' for c in match[0]),source)


def closing(mask,start,opening,ending):
    depth=0
    for position in range(start,len(mask)):
        if mask[position]==opening:depth+=1
        elif mask[position]==ending:
            depth-=1
            if depth==0:return position
    raise ValueError('unbalanced C definition')


def extract_function(source,name):
    if re.fullmatch(r'[A-Za-z_]\w*',name) is None:raise ValueError('invalid C function name')
    mask=code_mask(source);definitions=[]
    for match in re.finditer(r'\b'+re.escape(name)+r'\s*\(',mask):
        end=closing(mask,mask.index('(',match.start()),'(',')')
        body=end+1
        while body<len(mask) and mask[body].isspace():body+=1
        if body>=len(mask) or mask[body]!='{':continue
        # Only file-scope declarations are supported. Nested/macro definitions
        # and conditional signatures require an explicit parser upgrade.
        start=max(mask.rfind(';',0,match.start()),mask.rfind('}',0,match.start()))+1
        signature=mask[start:match.start()]
        if '#' in signature or '{' in signature:raise ValueError('unsupported conditional C signature')
        while start<match.start() and source[start].isspace():start+=1
        finish=closing(mask,body,'{','}')+1
        definitions.append(source[start:finish])
    if len(definitions)!=1:raise ValueError('expected exactly one definition of '+name)
    return definitions[0]


def rename_tokens(source,names):
    mask=code_mask(source)
    matches=list(re.finditer(r'\b[A-Za-z_]\w*\b',mask))
    for match in reversed(matches):
        replacement=names.get(match[0])
        if replacement is not None:source=source[:match.start()]+replacement+source[match.end():]
    return source


def generate(template,source_root,*,version):
    if version!=VERSION:raise ValueError('borrowed internals require CPython '+VERSION)
    root=Path(source_root).resolve()
    directives=list(DIRECTIVE.finditer(template))
    if '@Borrow' in DIRECTIVE.sub('',template):raise ValueError('unsupported borrow directive')
    names={match[1]:match[4] for match in directives}
    if len(names)!=len(directives):raise ValueError('duplicate borrowed declaration')
    def expand(match):
        if match[3]!=version:raise ValueError('borrow directive version mismatch')
        source=(root/match[2]).resolve()
        if not source.is_relative_to(root):raise ValueError('borrow source escapes root')
        return rename_tokens(extract_function(source.read_text(encoding='utf-8-sig'),match[1]),names)
    return '// Generated by tools/generate_borrowed.py for CPython '+version+'.\n'+DIRECTIVE.sub(expand,template)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-root',type=Path,default=Path(__file__).parent/'borrowed/cpython-3.14.4')
    args=parser.parse_args()
    root=Path(__file__).resolve().parents[1]
    template=(root/'tools/borrowed/borrowed_314.c.template').read_text()
    (root/'src/recompyler/ir/borrowed_314.c').write_text(generate(template,args.source_root,version=VERSION))


if __name__=='__main__':main()
